import { test, mock } from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import { join } from 'node:path';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { chromium } from 'playwright';
import type { Server } from 'node:http';
import { inquiryFixture } from './fixtures/integration-inquiry';
test('C4 browser: configure disabled, one-time secret, toggle, delivery log/retry, rotate and bilingual mobile UI', { timeout: 120000 }, async () => {
    const f = await inquiryFixture();
    let server: Server | undefined, browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
    try {
        const network = await import('../src/services/integration-webhook-http');
        mock.method(network.webhookNetwork, 'lookup', async () => [{ address: '8.8.8.8', family: 4 }] as any);
        const service = await import('../src/services/integration-webhook.service');
        const host = express();
        host.use((req, res, next) => req.path.startsWith('/api/') ? f.app(req, res, next) : next());
        host.use(express.static(join(__dirname, '../../web/dist')));
        host.get('*', (_req, res) => res.sendFile(join(__dirname, '../../web/dist/index.html')));
        server = await new Promise<Server>(r => { const s = host.listen(0, '127.0.0.1', () => r(s)); });
        const base = 'http://127.0.0.1:' + (server.address() as any).port;
        (await import('../src/config/env')).default.corsOrigins.push(base);
        browser = await chromium.launch({ headless: true });
        const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
        await context.addCookies([{ name: 'cdlm_access', value: f.tokenFor(f.manager), url: base, httpOnly: true, sameSite: 'Lax' }, { name: 'cdlm_csrf', value: 'fictional-csrf', url: base, sameSite: 'Lax' }]);
        const page = await context.newPage(), errors: string[] = [];
        page.on('pageerror', () => errors.push('browser-runtime-error'));
        await page.goto(base + '/projects/integrations');
        await page.getByRole('heading', { name: '状态与成交通知', exact: true }).waitFor();
        await page.getByLabel('接收地址（HTTPS）', { exact: true }).fill('https://receiver.fixture.org/hooks/crm');
        await page.getByRole('button',{name:'Switch to English',exact:true}).click();assert.equal(await page.getByLabel('Receiver URL (HTTPS)',{exact:true}).inputValue(),'https://receiver.fixture.org/hooks/crm');await page.getByRole('button',{name:'切换到中文',exact:true}).click();
        assert.equal(await page.getByLabel('启用事件通知', { exact: true }).isChecked(), false);
        await page.getByRole('button', { name: '保存', exact: true }).click();
        await page.getByRole('heading', { name: '保存签名密钥', exact: true }).waitFor();
        const secret = (await page.locator('[data-webhook-secret]').textContent())!;
        assert(/^[a-f0-9]{64}$/.test(secret));
        await page.getByRole('button', { name: '我已保存，关闭', exact: true }).click();
        await page.locator('[data-webhook-secret]').waitFor({ state: 'detached' });
        assert(await page.evaluate(v => !JSON.stringify([localStorage, sessionStorage]).includes(v), secret));
        await page.getByLabel('启用事件通知', { exact: true }).check();
        await page.getByRole('button', { name: '保存', exact: true }).click();
        await page.getByText('操作已完成', { exact: true }).waitFor();
        const c = await f.asA(() => f.m.IntegrationWebhook.findOne({ projectId: f.project._id }));
        const customer = await f.asA(() => f.m.Customer.create({ projectId: f.project._id, name: 'Fictional Event Buyer', status: 'pending', globalSiteSource: true }));
        await f.asA(() => f.m.IntegrationInquiry.create({ projectId: f.project._id, customerId: customer._id, externalInquiryId: 'fictional-c4-ui-inquiry', requestHash: 'fictional', secret: { fictional: true }, submittedAt: new Date(), sourceSystem: 'globalsite', notifyUserIds: [], readBy: [] }));
        await f.asA(() => f.m.CustomerEvent.create({ projectId: f.project._id, customerId: customer._id, type: 'status_changed', fromStatus: 'pending', toStatus: 'interested', at: new Date() }));
        mock.method(service.webhookTransport, 'post', async () => ({ status: 500 }));
        await f.asA(() => service.tickWebhookConfig(String(c._id), String(f.project._id)));
        // Use the receiver URL form's closest card; existing credential logs have their own refresh control.
        const card = page.getByRole('heading', { name: '状态与成交通知', exact: true }).locator('xpath=../..');
        await card.getByRole('button', { name: '刷新', exact: true }).last().click();
        await page.getByRole('button', { name: '查看投递日志', exact: true }).waitFor();
        await page.getByRole('button', { name: '查看投递日志', exact: true }).click();
        await page.getByRole('dialog').getByText('HTTP 500', { exact: false }).waitFor();
        await page.keyboard.press('Escape');
        const retried = page.waitForResponse(r => r.url().endsWith('/retry') && r.request().method() === 'POST');
        await page.getByRole('button', { name: '重新投递', exact: true }).click();
        assert.equal((await retried).status(), 200);
        mock.method(service.webhookTransport, 'post', async () => ({ status: 204 }));
        await f.asA(() => service.tickWebhookConfig(String(c._id), String(f.project._id)));
        await card.getByRole('button', { name: '刷新', exact: true }).last().click();
        await page.locator('article').getByText('已确认接收', { exact: true }).waitFor();
        page.once('dialog', d => void d.accept());
        await page.getByRole('button', { name: '更换签名密钥', exact: true }).click();
        await page.locator('[data-webhook-secret]').waitFor();
        assert((await page.locator('[data-webhook-secret]').textContent()) !== secret);
        await page.getByRole('button', { name: '我已保存，关闭', exact: true }).click();
        await page.locator('[data-webhook-secret]').waitFor({ state: 'detached' });
        const out = await mkdtemp(join(tmpdir(), 'globalcrm-c4-ui-'));
        await page.getByRole('heading', { name: '状态与成交通知', exact: true }).scrollIntoViewIfNeeded();
        assert.equal(await page.locator('[data-webhook-secret]').count(), 0);
        await page.screenshot({ path: join(out, 'desktop-zh.png'), fullPage: false });
        await page.setViewportSize({ width: 390, height: 844 });
        await page.getByRole('heading', { name: '状态与成交通知', exact: true }).scrollIntoViewIfNeeded();
        assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
        await page.screenshot({ path: join(out, 'mobile-zh.png'), fullPage: false });
        await page.getByRole('button', { name: 'Switch to English', exact: true }).click();
        await page.getByRole('heading', { name: 'Status and outcome notifications', exact: true }).waitFor();
        await page.setViewportSize({ width: 844, height: 390 });
        assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
        await page.screenshot({ path: join(out, 'landscape-en.png'), fullPage: false });
        assert.equal(errors.length, 0);
        console.log('C4 fictional UI screenshots: ' + out);
        await context.close();
    }
    finally {
        await browser?.close();
        if (server)
            await new Promise<void>(r => server!.close(() => r()));
        mock.restoreAll();
        await f.cleanup();
    }
});
