import test from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import type { Server } from 'node:http';
import { chromium, type Browser } from 'playwright';
import { randomBytes, generateKeyPairSync, createHash } from 'node:crypto';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { mkdtemp, writeFile, mkdir } from 'node:fs/promises';
import { inquiryFixture } from './fixtures/integration-inquiry';
test('C5 browser: one-time secret, consent, account return, revoke, bilingual mobile UI', { timeout: 120000 }, async () => {
    const f = await inquiryFixture();
    let uiServer: Server | undefined, browser: Browser | undefined;
    try {
        const models = await import('../src/models/OAuth');
        for (const model of models.oauthModels)
            await model.init();
        const privateKey = generateKeyPairSync('rsa', { modulusLength: 2048 }).privateKey.export({ format: 'jwk' });
        Object.assign(privateKey, { kid: 'fictional-ui-only', alg: 'RS256', use: 'sig' });
        const keyPath = join(f.temp, 'c5-ui-keyring.json');
        await writeFile(keyPath, JSON.stringify({ keys: [privateKey] }));
        const password = 'Fictional-C5-' + randomBytes(16).toString('hex');
        const owner = await f.asA(async () => f.m.User.create({ organizationId: f.org._id, username: 'fictional-c5-ui-owner', displayName: 'Fictional Owner', isPlatformAdmin: true, role: 'admin', passwordHash: await f.m.hashPassword(password), projectIds: [f.project._id] }));
        const ui = express();
        ui.use((req, res, next) => req.path.startsWith('/api/') || req.path.startsWith('/oidc/') ? f.app(req, res, next) : next());
        ui.get('/fixture/callback', (_req, res) => res.type('html').send('<p>Fictional callback</p>'));
        ui.use(express.static(join(__dirname, '../../web/dist')));
        ui.get('*', (_req, res) => res.sendFile(join(__dirname, '../../web/dist/index.html')));
        uiServer = await new Promise<Server>(resolve => { const s = ui.listen(0, '127.0.0.1', () => resolve(s)); });
        const base = 'http://127.0.0.1:' + (uiServer.address() as any).port;
        Object.assign(process.env, { OIDC_ENABLED: 'true', OIDC_ALLOW_LOOPBACK: 'true', OIDC_ISSUER: base + '/oidc', OIDC_PUBLIC_WEB_ORIGIN: base, OIDC_SIGNING_KEYRING_PATH: keyPath, OIDC_ACTIVE_KEY_ID: 'fictional-ui-only' });
        (await import('../src/config/env')).default.corsOrigins.push(base);
        browser = await chromium.launch({ headless: true });
        const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
        await context.addInitScript("Object.defineProperty(navigator,'clipboard',{value:{writeText:async()=>{window.c5CopyCount=(window.c5CopyCount||0)+1;}},configurable:true});");
        assert.equal((await context.request.post(base + '/api/auth/login', { data: { username: owner.username, password } })).status(), 200);
        const page = await context.newPage(), errors: string[] = [];
        page.on('pageerror', () => errors.push('browser-runtime-error'));
        await page.goto(base + '/platform/oauth-clients');
        await page.getByRole('heading', { name: '登录应用登记', exact: true }).waitFor();
        await page.getByRole('button', { name: '登记应用', exact: true }).click();
        let dialog = page.getByRole('dialog');
        await dialog.getByLabel('应用名称', { exact: true }).fill('Fictional GlobalSite');
        await dialog.getByLabel('运营方', { exact: true }).fill('Fictional Operator');
        await dialog.getByLabel('隐私政策', { exact: true }).fill('https://site.example.test/privacy');
        await dialog.getByLabel('服务条款', { exact: true }).fill('https://site.example.test/terms');
        await dialog.getByLabel('回调地址', { exact: false }).fill(base + '/fixture/callback');
        await dialog.getByRole('button', { name: '登记应用', exact: true }).click();
        await page.getByRole('heading', { name: '保存应用密钥' }).waitFor();
        const secret = (await page.getByRole('dialog').locator('code').textContent())!;
        assert(secret.length >= 43);
        await page.getByRole('button', { name: '复制密钥', exact: true }).click();
        await page.getByRole('button', { name: '已复制', exact: true }).waitFor();
        await page.getByRole('button', { name: '我已保存，关闭', exact: true }).click();
        await page.getByRole('dialog').waitFor({ state: 'detached' });
        assert(await page.evaluate(value => !JSON.stringify([localStorage, sessionStorage]).includes(value), secret));
        await page.reload();
        await page.getByText('Fictional GlobalSite', { exact: true }).waitFor();
        const client = (await f.asA(() => models.OAuthClient.findOne({ name: 'Fictional GlobalSite' }).lean()))!;
        const viewer = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
        assert.equal((await viewer.request.post(base + '/api/auth/login', { data: { username: f.viewer.username, password: 'Fictional-J1-Login-Only' } })).status(), 200);
        const consent = await viewer.newPage();
        consent.on('pageerror', () => errors.push('browser-runtime-error'));
        const verifier = randomBytes(32).toString('base64url'), state = randomBytes(32).toString('base64url'), nonce = randomBytes(32).toString('base64url');
        const params = new URLSearchParams({ client_id: client.clientId, response_type: 'code', redirect_uri: client.redirectUris[0], scope: 'openid profile crm.context offline_access', state, nonce, prompt: 'consent', code_challenge: createHash('sha256').update(verifier).digest('base64url'), code_challenge_method: 'S256' });
        await consent.goto(base + '/oidc/auth?' + params);
        await consent.getByRole('heading', { name: '授权使用 CRM 账号登录', exact: true }).waitFor();
        assert.equal(await consent.getByRole('button', { name: '同意并继续', exact: true }).isDisabled(), true);
        const offline = consent.getByRole('checkbox', { name: /保持登录/ });
        assert.equal(await offline.isChecked(), false);
        await consent.getByLabel('选择授权项目', { exact: true }).selectOption(String(f.project._id));
        const output = process.env.C5_UI_SCREENSHOTS ?? await mkdtemp(join(tmpdir(), 'globalcrm-c5-ui-preview-'));
        await mkdir(output, { recursive: true });
        await consent.screenshot({ path: join(output, 'consent-desktop.png'), fullPage: true });
        await consent.getByRole('button', { name: '同意并继续', exact: true }).click();
        await consent.waitForURL(base + '/fixture/callback*');
        const callback = new URL(consent.url());
        assert.equal(callback.searchParams.get('state'), state);
        const response = await fetch(base + '/oidc/token', { method: 'POST', headers: { Authorization: 'Basic ' + Buffer.from(client.clientId + ':' + secret).toString('base64'), 'Content-Type': 'application/x-www-form-urlencoded' }, body: new URLSearchParams({ grant_type: 'authorization_code', code: callback.searchParams.get('code')!, code_verifier: verifier, redirect_uri: client.redirectUris[0] }) });
        assert.equal(response.status, 200);
        const token = await response.json() as any;
        assert(!token.refresh_token);
        await consent.goto(base + '/security/applications');
        await consent.getByRole('heading', { name: '已授权应用', exact: true }).waitFor();
        await consent.getByText('Fictional GlobalSite', { exact: true }).waitFor();
        await consent.setViewportSize({ width: 390, height: 844 });
        assert(await consent.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
        await consent.screenshot({ path: join(output, 'applications-mobile.png'), fullPage: true });
        await consent.getByRole('button', { name: '撤销授权', exact: true }).click();
        dialog = consent.getByRole('dialog');
        await dialog.getByRole('button', { name: '确认', exact: true }).click();
        await consent.getByRole('dialog').waitFor({ state: 'detached' });
        await consent.getByText('已撤销', { exact: true }).waitFor();
        assert.equal((await fetch(base + '/oidc/me', { headers: { Authorization: 'Bearer ' + token.access_token } })).status, 401);
        await consent.setViewportSize({ width: 1440, height: 1000 });
        await consent.getByRole('button', { name: 'Switch to English', exact: true }).click();
        await consent.getByRole('heading', { name: 'Authorized applications', exact: true }).waitFor();
        assert.equal(errors.length, 0);
        console.log('C5 fictional UI screenshots: ' + output);
        await context.close();
        await viewer.close();
    }
    finally {
        delete process.env.OIDC_ENABLED;
        await browser?.close();
        if (uiServer)
            await new Promise<void>(resolve => uiServer!.close(() => resolve()));
        await f.cleanup();
    }
});
