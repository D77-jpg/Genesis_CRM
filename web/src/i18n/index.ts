const dictionaries: Record<Language, Record<TranslationKey, string>> = { zh, en };
let current: Language = readLanguage();
const listeners = new Set<() => void>();

function readLanguage(): Language {
  try {
    const stored = localStorage.getItem(STORAGE_KEYS.language);
    if (stored === 'en' || stored === 'zh') return stored;
  } catch { /* private mode */ }
  // Chinese is the default for this product; browser English is an opt-in.
  return 'zh';
}

function applyDocumentLanguage(language: Language): void {
  if (typeof document !== 'undefined') document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
}

applyDocumentLanguage(current);

export function getLanguage(): Language {
  return current;
}

export function setLanguage(language: Language): void {
  if (language === current) return;
  current = language;
  try { localStorage.setItem(STORAGE_KEYS.language, language); } catch { /* ignore */ }
  applyDocumentLanguage(language);
  listeners.forEach((listener) => listener());
}

export function subscribeLanguage(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

