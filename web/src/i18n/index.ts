export function translateText(text: string, allowPhrases = true): string {
  if (current !== 'en') return text;
  const trimmed = text.trim();
  if (!trimmed) return text;
  const exact = AUTO_TRANSLATIONS[trimmed];
  if (exact !== undefined) return text.replace(trimmed, exact);
  const dynamic = translateDynamic(trimmed);
  if (dynamic) return text.replace(trimmed, dynamic);
  if (!allowPhrases || trimmed.length < 2) return text;
  let translated = trimmed;
  for (const [zh, en] of sortedPhrases) {
    if (zh.length < 2) continue;
    translated = translated.split(zh).join(en);
  }
  if (translated === trimmed || /[\u4e00-\u9fff]/.test(translated)) return text;
  return text.replace(trimmed, translated.replace(/\s{2,}/g, ' '));
}

export function translate(key: TranslationKey, vars?: Record<string, string | number>): string {
  const template = dictionaries[current][key] ?? zh[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => String(vars[name] ?? `{${name}}`));
}

export function useI18n(): { language: Language; setLanguage: (language: Language) => void; t: (key: TranslationKey, vars?: Record<string, string | number>) => string } {
  const language = React.useSyncExternalStore(subscribeLanguage, getLanguage, getLanguage);
  React.useEffect(() => { applyDocumentLanguage(language); }, [language]);
  // Keep `t` stable per language: pages use it in useCallback/useEffect
  // dependency arrays, and a fresh function on every render causes request loops.
  const t = React.useCallback((key: TranslationKey, vars?: Record<string, string | number>) => {
    const template = dictionaries[language][key] ?? zh[key] ?? key;
    return vars ? template.replace(/\{(\w+)\}/g, (_match, name: string) => String(vars[name] ?? `{${name}}`)) : template;
  }, [language]);
  return React.useMemo(() => ({ language, setLanguage, t }), [language, t]);
}
